"""Witness for the K_6-on-2x6-ladder claim (theory 3.3, fig:k6-ladder).

Six logical qubits, two rails each, on the 12 sites of a 2x6 ladder (zero spare
sites). Exhibits an explicit assignment and INDEPENDENTLY verifies all
binom(6,2)=15 logical pairs have an adjacent rail pair, i.e. K_6 is realized
with zero routing overhead. Also emits the tikz body for the paper figure.

    .venv/bin/python k6_ladder_witness.py
"""

from __future__ import annotations

import networkx as nx

from embed_search import embeds, grid


def main():
    n = 6
    H = nx.complete_graph(n)          # K_6 logical interaction graph
    G = grid(2, 6)                    # 2x6 ladder, sites 0..11 (row = s//6, col = s%6)
    placement = embeds(H, G, tokens_per_vertex=2, time_limit=120.0)
    assert placement is not None, "no embedding found (claim would be FALSE)"

    rc = lambda s: (s // 6, s % 6)
    Gedges = {frozenset(e) for e in G.edges()}

    # Independent re-check: every logical pair has an adjacent rail pair.
    realized = []
    for i, j in ((a, b) for a in range(n) for b in range(a + 1, n)):
        ok = any(
            frozenset((ri, rj)) in Gedges
            for ri in placement[i]
            for rj in placement[j]
        )
        realized.append(((i, j), ok))
    n_ok = sum(ok for _, ok in realized)

    # Sites must be distinct and fill all 12 (tight, zero spare).
    sites = [s for toks in placement.values() for s in toks]
    assert len(sites) == len(set(sites)) == 12, "sites not a tight 12-site fill"

    print("=== K_6 on 2x6 ladder: explicit assignment ===")
    print("logical  rail0(row,col)  rail1(row,col)  sites")
    for q in range(n):
        r0, r1 = placement[q]
        print(f"  q{q}      {rc(r0)}          {rc(r1)}          {r0:>2d},{r1:>2d}")
    print(f"\nrealized logical pairs: {n_ok}/15")
    miss = [p for p, ok in realized if not ok]
    print("VERDICT:", "K_6 fully realized, zero routing overhead, zero spare sites"
          if n_ok == 15 else f"INCOMPLETE, missing {miss}")

    # --- tikz body for figures/k6_ladder.tex ---
    print("\n=== tikz body (figures/k6_ladder.tex) ===")
    site_q = {s: q for q in range(n) for s in placement[q]}
    site_rail = {q: list(placement[q]) for q in range(n)}
    colors = ["red!18", "blue!16", "green!22", "orange!22", "violet!20", "teal!22"]
    lines = [
        "% Generated by research/quotient_embedding/k6_ladder_witness.py (verified 15/15).",
        "\\begin{tikzpicture}[x=1.15cm,y=1.15cm,every node/.style={font=\\footnotesize}]",
    ]
    for s in range(12):  # nodes first
        r, c = rc(s)
        q = site_q[s]
        rail = site_rail[q].index(s)
        lines.append(
            f"  \\node[draw,circle,fill={colors[q]},inner sep=1.2pt] (s{s}) "
            f"at ({c},{0 if r == 0 else -1}) {{$q_{q}^{{{rail}}}$}};"
        )
    lines.append("  % ladder (hardware) edges: every one joins two distinct logical qubits")
    for a, b in (sorted(e) for e in G.edges()):
        lines.append(f"  \\draw[gray!55] (s{a}) -- (s{b});")
    lines.append("  % dashed: the two delocalized rails of each logical qubit (non-adjacent)")
    for q in range(n):
        a, b = site_rail[q]
        lines.append(f"  \\draw[dashed,gray!75] (s{a}) to[bend left=18] (s{b});")
    lines.append("\\end{tikzpicture}")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
